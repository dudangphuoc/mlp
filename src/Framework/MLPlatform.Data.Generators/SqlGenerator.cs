using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace MLPlatform.Data.Generators;

/// <summary>[SqlQuery("Module/Name.sql")] partial method → typed ADO.NET code (20/02 §5.2).</summary>
[Generator]
public sealed class SqlGenerator : IIncrementalGenerator
{
    private static readonly DiagnosticDescriptor ParamMismatch = new("MLPSQL001", "SQL parameter mismatch",
        "{0}: {1}", "MLPlatform.Sql", DiagnosticSeverity.Error, true);
    private static readonly DiagnosticDescriptor FileMissing = new("MLPSQL002", "SQL file not found",
        "'{0}' not found in AdditionalFiles (Sql/**/*.sql)", "MLPlatform.Sql", DiagnosticSeverity.Error, true);
    private static readonly DiagnosticDescriptor BadHeader = new("MLPSQL003", "Invalid SQL header",
        "'{0}': missing line '-- mlp:query <Name> :one|:many|:exec|:scalar'", "MLPlatform.Sql", DiagnosticSeverity.Error, true);
    private static readonly DiagnosticDescriptor BadShape = new("MLPSQL004", "Invalid method signature",
        "{0}", "MLPlatform.Sql", DiagnosticSeverity.Error, true);

    private static readonly Regex ParamRx = new(@"(?<![:@\w])@([a-z_][a-z0-9_]*)", RegexOptions.Compiled);
    private static readonly Regex HeaderRx = new(@"^--\s*mlp:query\s+(\w+)\s+:(one|many|exec|scalar)", RegexOptions.Compiled | RegexOptions.Multiline);

    private static readonly SymbolDisplayFormat Fq = SymbolDisplayFormat.FullyQualifiedFormat
        .AddMiscellaneousOptions(SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);

    private sealed class MethodInfo
    {
        public IMethodSymbol Symbol = null!;
        public string Path = "";
        public Location Location = Location.None;
    }

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var sqlFiles = context.AdditionalTextsProvider
            .Where(static f => f.Path.EndsWith(".sql", StringComparison.OrdinalIgnoreCase))
            .Select(static (f, ct) => (Path: f.Path.Replace('\\', '/'), Text: f.GetText(ct)?.ToString() ?? ""))
            .Collect();

        var methods = context.SyntaxProvider.ForAttributeWithMetadataName(
                "MLPlatform.Data.SqlQueryAttribute",
                static (n, _) => n is MethodDeclarationSyntax,
                static (ctx, _) => new MethodInfo
                {
                    Symbol = (IMethodSymbol)ctx.TargetSymbol,
                    Path = ctx.Attributes[0].ConstructorArguments[0].Value as string ?? "",
                    Location = ctx.TargetNode.GetLocation(),
                })
            .Collect();

        context.RegisterSourceOutput(methods.Combine(sqlFiles), static (spc, pair) => Emit(spc, pair.Left, pair.Right));
    }

    private static void Emit(SourceProductionContext spc, ImmutableArray<MethodInfo> methods,
        ImmutableArray<(string Path, string Text)> files)
    {
        foreach (var group in methods.GroupBy(m => m.Symbol.ContainingType, SymbolEqualityComparer.Default))
        {
            var type = (INamedTypeSymbol)group.Key!;
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/> MLPlatform.Data.Generators");
            sb.AppendLine("#nullable enable");
            sb.AppendLine("#pragma warning disable CS1998");
            var ns = type.ContainingNamespace.IsGlobalNamespace ? null : type.ContainingNamespace.ToDisplayString();
            if (ns is not null) sb.AppendLine($"namespace {ns};");
            sb.AppendLine($"static partial class {type.Name}");
            sb.AppendLine("{");
            foreach (var m in group)
            {
                var file = files.FirstOrDefault(f => f.Path.EndsWith("/Sql/" + m.Path, StringComparison.Ordinal)
                                                     || f.Path.EndsWith("/" + m.Path, StringComparison.Ordinal));
                if (file.Path is null)
                {
                    spc.ReportDiagnostic(Diagnostic.Create(FileMissing, m.Location, m.Path));
                    continue;
                }
                EmitMethod(spc, sb, m, file.Text);
            }
            sb.AppendLine("}");
            spc.AddSource($"{type.Name}.Sql.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
        }
    }

    private static void EmitMethod(SourceProductionContext spc, StringBuilder sb, MethodInfo m, string sql)
    {
        var header = HeaderRx.Match(sql);
        if (!header.Success)
        {
            spc.ReportDiagnostic(Diagnostic.Create(BadHeader, m.Location, m.Path));
            return;
        }
        var kind = header.Groups[2].Value;
        var s = m.Symbol;
        if (!HasExtensionShape(s))
        {
            spc.ReportDiagnostic(Diagnostic.Create(BadShape, m.Location,
                $"{s.Name}: must be a static extension (this IReadSession|IWriteSession db, …, CancellationToken ct)"));
            return;
        }
        var body = StripComments(sql);
        var sqlParams = ParamRx.Matches(body).Cast<Match>().Select(x => x.Groups[1].Value).Distinct().ToList();
        var methodParams = s.Parameters.Skip(1).Take(s.Parameters.Length - 2).ToList();
        var byName = methodParams.ToDictionary(p => Snake(p.Name), p => p);
        ReportParamMismatches(spc, m, sqlParams, byName);
        var ret = (INamedTypeSymbol)s.ReturnType;
        var inner = ret.TypeArguments.Length == 1 ? ret.TypeArguments[0] : null;
        var db = s.Parameters[0];
        var ct = s.Parameters.Last().Name;
        var sig = string.Join(", ", s.Parameters.Select((p, i) =>
            (i == 0 ? "this " : "") + p.Type.ToDisplayString(Fq) + " " + p.Name));
        var access = SyntaxFacts(s.DeclaredAccessibility);
        sb.AppendLine($"    private const string __sql_{s.Name} = @\"{body.Replace("\"", "\"\"")}\";");
        sb.AppendLine();
        sb.AppendLine($"    {access} static async partial {ret.ToDisplayString(Fq)} {s.Name}({sig})");
        sb.AppendLine("    {");
        sb.AppendLine($"        var __conn = await {db.Name}.OpenAsync({ct});");
        sb.AppendLine($"        await using var __cmd = new global::Npgsql.NpgsqlCommand(__sql_{s.Name}, __conn, {db.Name}.Transaction);");
        foreach (var p in methodParams)
            sb.AppendLine($"        __cmd.Parameters.Add(new global::Npgsql.NpgsqlParameter(\"{Snake(p.Name)}\", {ToDb(p.Type, p.Name)}));");
        EmitExecution(sb, kind, inner, ct);
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static bool HasExtensionShape(IMethodSymbol s) =>
        s.IsStatic && s.IsExtensionMethod && s.Parameters.Length >= 2
        && s.Parameters.Last().Type.ToDisplayString() == "System.Threading.CancellationToken";

    private static void ReportParamMismatches(SourceProductionContext spc, MethodInfo m, List<string> sqlParams,
        Dictionary<string, IParameterSymbol> byName)
    {
        foreach (var sp in sqlParams.Where(p => !byName.ContainsKey(p)))
            spc.ReportDiagnostic(Diagnostic.Create(ParamMismatch, m.Location, m.Path, $"missing method parameter for @{sp}"));
        foreach (var mp in byName.Keys.Where(k => !sqlParams.Contains(k)))
            spc.ReportDiagnostic(Diagnostic.Create(ParamMismatch, m.Location, m.Path, $"parameter '{byName[mp].Name}' has no @{mp} in the SQL"));
    }

    private static void EmitExecution(StringBuilder sb, string kind, ITypeSymbol? inner, string ct)
    {
        switch (kind)
        {
            case "exec":
                sb.AppendLine($"        {(inner is null ? "" : "return ")}await __cmd.ExecuteNonQueryAsync({ct});");
                break;
            case "scalar":
                sb.AppendLine($"        var __v = await __cmd.ExecuteScalarAsync({ct});");
                sb.AppendLine($"        return __v is null or global::System.DBNull ? default({inner!.ToDisplayString(Fq)})! : {FromObj(inner!, "__v")};");
                break;
            case "one":
            case "many":
                var row = kind == "one" ? inner! : ((INamedTypeSymbol)inner!).TypeArguments[0];
                row = row.WithNullableAnnotation(NullableAnnotation.NotAnnotated);
                var ctor = ((INamedTypeSymbol)row).InstanceConstructors.OrderByDescending(c => c.Parameters.Length).First();
                sb.AppendLine($"        await using var __r = await __cmd.ExecuteReaderAsync({ct});");
                var read = string.Join(", ", ctor.Parameters.Select(cp =>
                    $"{Reader(cp.Type, $"__r.GetOrdinal(\"{Snake(cp.Name)}\")")}"));
                if (kind == "one")
                {
                    sb.AppendLine($"        if (!await __r.ReadAsync({ct})) return null;");
                    sb.AppendLine($"        return new {row.ToDisplayString(Fq)}({read});");
                }
                else
                {
                    sb.AppendLine($"        var __list = new global::System.Collections.Generic.List<{row.ToDisplayString(Fq)}>();");
                    sb.AppendLine($"        while (await __r.ReadAsync({ct})) __list.Add(new {row.ToDisplayString(Fq)}({read}));");
                    sb.AppendLine("        return __list;");
                }
                break;
        }
    }

    private static string SyntaxFacts(Accessibility a) => a switch
    {
        Accessibility.Public => "public",
        Accessibility.Internal => "internal",
        Accessibility.Private => "private",
        _ => "internal",
    };

    private static bool IsEnum(ITypeSymbol t) => t.TypeKind == TypeKind.Enum;

    private static ITypeSymbol Underlying(ITypeSymbol t, out bool nullable)
    {
        nullable = t.NullableAnnotation == NullableAnnotation.Annotated;
        if (t is INamedTypeSymbol n && n.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T)
        {
            nullable = true;
            return n.TypeArguments[0];
        }
        return t.WithNullableAnnotation(NullableAnnotation.NotAnnotated);
    }

    private static string ToDb(ITypeSymbol t, string name)
    {
        var u = Underlying(t, out var nullable);
        if (IsEnum(u))
            return nullable
                ? $"{name}.HasValue ? global::MLPlatform.Data.SqlMapping.EnumToDb({name}.Value) : (object)global::System.DBNull.Value"
                : $"global::MLPlatform.Data.SqlMapping.EnumToDb({name})";
        return nullable ? $"(object?){name} ?? global::System.DBNull.Value" : name;
    }

    private static string Reader(ITypeSymbol t, string ord)
    {
        var u = Underlying(t, out var nullable);
        var fq = u.ToDisplayString(Fq);
        string get = IsEnum(u)
            ? $"global::MLPlatform.Data.SqlMapping.EnumFromDb<{fq}>(__r.GetFieldValue<string>({ord}))"
            : $"__r.GetFieldValue<{fq}>({ord})";
        return nullable ? $"(__r.IsDBNull({ord}) ? default({t.ToDisplayString(Fq)}) : {get})" : get;
    }

    private static string FromObj(ITypeSymbol t, string v)
    {
        var u = Underlying(t, out _);
        var fq = u.ToDisplayString(Fq);
        if (IsEnum(u)) return $"global::MLPlatform.Data.SqlMapping.EnumFromDb<{fq}>((string){v})";
        if (u.SpecialType == SpecialType.System_Int64) return $"global::System.Convert.ToInt64({v})";
        if (u.SpecialType == SpecialType.System_Int32) return $"global::System.Convert.ToInt32({v})";
        return $"({fq}){v}";
    }

    private static string StripComments(string sql) =>
        string.Join("\n", sql.Split('\n').Where(l => !l.TrimStart().StartsWith("--"))).Trim();

    internal static string Snake(string name)
    {
        var sb = new StringBuilder();
        for (var i = 0; i < name.Length; i++)
        {
            var c = name[i];
            if (char.IsUpper(c))
            {
                if (i > 0) sb.Append('_');
                sb.Append(char.ToLowerInvariant(c));
            }
            else sb.Append(c);
        }
        return sb.ToString();
    }
}
