using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace MLPlatform.Cqrs.Generators;

/// <summary>Generates explicit DI registration + a type-switch mediator dispatch (no reflection; 20/02 §4).</summary>
[Generator]
public sealed class CqrsGenerator : IIncrementalGenerator
{
    private const string CommandHandler = "MLPlatform.Cqrs.ICommandHandler`2";
    private const string QueryHandler = "MLPlatform.Cqrs.IQueryHandler`2";

    private sealed class HandlerInfo
    {
        public string Handler = "";
        public string Request = "";
        public string Result = "";
        public bool IsCommand;
        public string? Permission;
        public bool HasWorkspace;
    }

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var handlers = context.SyntaxProvider.CreateSyntaxProvider(
                static (node, _) => node is ClassDeclarationSyntax c && c.BaseList is not null,
                static (ctx, _) => Collect(ctx))
            .Where(static h => h is not null)
            .Collect();

        var assemblyName = context.CompilationProvider.Select(static (c, _) => c.AssemblyName ?? "Assembly");

        context.RegisterSourceOutput(handlers.Combine(assemblyName),
            static (spc, pair) => Emit(spc, pair.Left!, pair.Right));
    }

    private static HandlerInfo? Collect(GeneratorSyntaxContext ctx)
    {
        if (ctx.SemanticModel.GetDeclaredSymbol(ctx.Node) is not INamedTypeSymbol type || type.IsAbstract)
            return null;
        foreach (var i in type.AllInterfaces)
        {
            var def = i.OriginalDefinition.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)
                .Replace("global::", "");
            var meta = i.OriginalDefinition.ContainingNamespace.ToDisplayString() + "." + i.OriginalDefinition.MetadataName;
            var isCmd = meta == CommandHandler;
            if (!isCmd && meta != QueryHandler) continue;
            var request = (INamedTypeSymbol)i.TypeArguments[0];
            var perm = request.GetAttributes()
                .FirstOrDefault(a => a.AttributeClass?.ToDisplayString() == "MLPlatform.Cqrs.RequiresPermissionAttribute")
                ?.ConstructorArguments.FirstOrDefault().Value as string;
            _ = def;
            return new HandlerInfo
            {
                Handler = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
                Request = request.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
                Result = i.TypeArguments[1].ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
                IsCommand = isCmd,
                Permission = perm,
                HasWorkspace = request.GetMembers("WorkspaceId").OfType<IPropertySymbol>()
                    .Any(p => p.Type.ToDisplayString() is "System.Guid" or "System.Guid?"),
            };
        }
        return null;
    }

    private static void Emit(SourceProductionContext spc, ImmutableArray<HandlerInfo?> items, string assembly)
    {
        var list = items.Where(x => x is not null).Select(x => x!)
            .GroupBy(x => x.Request).Select(g => g.First()).OrderBy(x => x.Request).ToList();
        if (list.Count == 0) return;
        var ns = assembly + ".Generated";
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/> MLPlatform.Cqrs.Generators");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using Microsoft.Extensions.DependencyInjection;");
        sb.AppendLine("using MLPlatform.Cqrs;");
        sb.AppendLine($"namespace {ns};");
        sb.AppendLine();
        sb.AppendLine("[global::System.CodeDom.Compiler.GeneratedCode(\"MLPlatform.Cqrs.Generators\", \"1.0\")]");
        sb.AppendLine("public static class CqrsRegistration");
        sb.AppendLine("{");
        sb.AppendLine("    /// <summary>Registers every handler + the generated mediator.</summary>");
        sb.AppendLine("    public static IServiceCollection AddGeneratedHandlers(this IServiceCollection services)");
        sb.AppendLine("    {");
        foreach (var h in list)
            sb.AppendLine($"        services.AddScoped<{h.Handler}>();");
        sb.AppendLine("        services.AddScoped<IMediator, GeneratedMediator>();");
        sb.AppendLine("        return services;");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>Known requests (name, command?, permission); used for gates/docs.</summary>");
        sb.AppendLine("    public static readonly (string Name, bool IsCommand, string? Permission)[] Requests =");
        sb.AppendLine("    [");
        foreach (var h in list)
            sb.AppendLine($"        (\"{Short(h.Request)}\", {(h.IsCommand ? "true" : "false")}, {Lit(h.Permission)}),");
        sb.AppendLine("    ];");
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("[global::System.CodeDom.Compiler.GeneratedCode(\"MLPlatform.Cqrs.Generators\", \"1.0\")]");
        sb.AppendLine("internal sealed class GeneratedMediator(global::System.IServiceProvider sp, global::System.Collections.Generic.IEnumerable<IRequestBehavior> behaviors) : IMediator");
        sb.AppendLine("{");
        sb.AppendLine("    private readonly IRequestBehavior[] _behaviors = global::System.Linq.Enumerable.ToArray(behaviors);");
        sb.AppendLine();
        EmitDispatch(sb, list.Where(h => h.IsCommand).ToList(), "Send", "ICommand");
        EmitDispatch(sb, list.Where(h => !h.IsCommand).ToList(), "Query", "IQuery");
        sb.AppendLine("}");
        spc.AddSource("Cqrs.g.cs", sb.ToString());
    }

    private static void EmitDispatch(StringBuilder sb, List<HandlerInfo> hs, string method, string iface)
    {
        sb.AppendLine($"    public async global::System.Threading.Tasks.ValueTask<TResult> {method}<TResult>({iface}<TResult> request, global::System.Threading.CancellationToken ct = default)");
        sb.AppendLine("    {");
        sb.AppendLine("        object? result = request switch");
        sb.AppendLine("        {");
        foreach (var h in hs)
        {
            sb.AppendLine($"            {h.Request} r => await Pipeline.Run(_behaviors,");
            sb.AppendLine($"                new RequestContext(r, \"{Short(h.Request)}\", {(h.IsCommand ? "true" : "false")}, {Lit(h.Permission)}, {(h.HasWorkspace ? "r.WorkspaceId" : "null")}),");
            sb.AppendLine($"                async () => (object?)await sp.GetRequiredService<{h.Handler}>().Handle(r, ct), ct),");
        }
        sb.AppendLine($"            _ => throw new global::System.InvalidOperationException(\"No handler for \" + request.GetType().Name),");
        sb.AppendLine("        };");
        sb.AppendLine("        return (TResult)result!;");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static string Short(string fq) => fq.Substring(fq.LastIndexOf('.') + 1);
    private static string Lit(string? s) => s is null ? "null" : "\"" + s.Replace("\"", "\\\"") + "\"";
}
