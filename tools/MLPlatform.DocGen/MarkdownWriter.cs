using System.Text;
using Google.Protobuf.Reflection;

namespace MLPlatform.DocGen;

/// <summary>Markdown tables generated from the model; never edited by hand.</summary>
public static class MarkdownWriter
{
    private const string Banner = "<!-- Generated by tools/MLPlatform.DocGen from code; do not edit. Regenerate: dotnet tools/MLPlatform.DocGen/bin/Debug/net11.0/mlp-docgen.dll . -->\n\n";

    public static IEnumerable<(string Path, string Text)> Write(ApiModel model)
    {
        yield return ("README.md", Index(model));
        yield return ("modules.md", Modules(model));
        yield return ("rest.md", Rest(model));
        foreach (var service in model.Services) yield return ($"api/{service.Name}.md", Service(model, service));
        foreach (var file in model.ProtoFiles.Where(f => f.MessageTypes.Count > 0)) yield return ($"types/{Path.GetFileNameWithoutExtension(file.Name)}.md", Types(file));
        foreach (var schema in model.Tables.GroupBy(t => t.Schema)) yield return ($"db/{schema.Key}.md", Database(schema.Key, [.. schema]));
    }

    private static string Index(ApiModel model)
    {
        var sb = new StringBuilder(Banner).Append("# MLPlatform API and data reference\n\n");
        sb.Append("| Area | Count |\n|---|---:|\n");
        sb.Append($"| gRPC services | {model.Services.Count()} |\n| gRPC methods | {model.Services.Sum(s => s.Methods.Count)} |\n");
        sb.Append($"| REST routes | {model.RestRoutes.Count} |\n| Commands and queries | {model.Requests.Count} |\n");
        sb.Append($"| Modules | {model.Modules.Count} |\n| Database tables | {model.Tables.Count} |\n\n");
        sb.Append("- [Modules and layers](modules.md)\n- [REST routes](rest.md)\n");
        foreach (var s in model.Services) sb.Append($"- [{s.Name}](api/{s.Name}.md)\n");
        foreach (var schema in model.Tables.Select(t => t.Schema).Distinct()) sb.Append($"- [Database schema `{schema}`](db/{schema}.md)\n");
        return sb.ToString();
    }

    private static string Modules(ApiModel model)
    {
        var sb = new StringBuilder(Banner).Append("# Modules and layers\n\n```mermaid\nflowchart TB\n");
        foreach (var layer in model.Modules.GroupBy(m => m.Layer).Reverse())
        {
            sb.Append($"  subgraph {layer.Key}\n");
            foreach (var m in layer) sb.Append($"    {m.Name}\n");
            sb.Append("  end\n");
        }
        foreach (var m in model.Modules) foreach (var u in m.Uses) sb.Append($"  {m.Name} --> {u}\n");
        sb.Append("```\n\nLower layers never depend on higher ones (gate MLPARCH001); arrows are the declared same-layer dependencies.\n\n");
        sb.Append("| Module | Layer | Requests | SQL folders | Shared SQL | Spec |\n|---|---|---:|---|---|---|\n");
        foreach (var m in model.Modules)
        {
            var shared = m.PublicSql ? "all" : string.Join(", ", m.Api);
            sb.Append($"| {m.Name} | {m.Layer} | {model.Requests.Count(r => r.Module == m.Name)} | {string.Join(", ", m.SqlFolders)} | {shared} | [{Path.GetFileName(m.Spec)}](../../{m.Spec}) |\n");
        }
        return sb.ToString();
    }

    private static string Rest(ApiModel model)
    {
        var sb = new StringBuilder(Banner).Append("# REST routes\n\n| Verb | Path | Area | Public |\n|---|---|---|---|\n");
        foreach (var r in model.RestRoutes) sb.Append($"| {r.Verb} | `{r.Path}` | {r.Area} | {(r.IsPublic ? "yes" : "")} |\n");
        return sb.ToString();
    }

    private static string Service(ApiModel model, ServiceDescriptor service)
    {
        var sb = new StringBuilder(Banner).Append($"# {service.Name}\n\nPath prefix: `/{service.FullName}/`\n\n");
        sb.Append("| Method | Request → Response | Effect | Access | Permission | Roles | Sends |\n|---|---|---|---|---|---|---|\n");
        foreach (var m in service.Methods)
        {
            var requests = model.RequestsFor(m).ToList();
            var primary = OperationTraits.Primary(requests);
            var stream = m.IsServerStreaming ? " (stream)" : "";
            sb.Append($"| {m.Name}{stream} | {TypeLink(m.InputType)} → {TypeLink(m.OutputType)} | {OperationTraits.Effect(m, requests)} | {primary?.Access ?? ""} | ");
            sb.Append($"{primary?.Permission ?? ""} | {string.Join(", ", primary?.Roles ?? [])} | {string.Join(", ", requests.Select(r => $"{r.Module}.{r.ShortName}"))} |\n");
        }
        return sb.ToString();
    }

    private static string TypeLink(MessageDescriptor type) =>
        $"[{type.Name}](../types/{Path.GetFileNameWithoutExtension(type.File.Name)}.md#{type.Name.ToLowerInvariant()})";

    private static string Types(FileDescriptor file)
    {
        var sb = new StringBuilder(Banner).Append($"# Types in `{file.Name}`\n\n");
        foreach (var message in file.MessageTypes)
        {
            sb.Append($"## {message.Name}\n\n| Field | # | Type |\n|---|---:|---|\n");
            foreach (var f in message.Fields.InFieldNumberOrder()) sb.Append($"| {f.Name} | {f.FieldNumber} | {ProtoTypes.Describe(f)} |\n");
            sb.Append('\n');
        }
        foreach (var e in file.EnumTypes)
            sb.Append($"## {e.Name}\n\n{string.Join(", ", e.Values.Select(v => $"`{v.Name}`"))}\n\n");
        return sb.ToString();
    }

    private static string Database(string schema, List<DbTable> tables)
    {
        var sb = new StringBuilder(Banner).Append($"# Database schema `{schema}`\n\n");
        foreach (var t in tables)
        {
            sb.Append($"## {t.FullName}\n\n| Column | Type | Null | Default |\n|---|---|---|---|\n");
            foreach (var c in t.Columns) sb.Append($"| {c.Name} | {c.Type} | {(c.Nullable ? "yes" : "")} | {c.Default?.Replace("|", "\\|") ?? ""} |\n");
            sb.Append($"\nWritten by: {Queries(t.WrittenBy)}\n\nRead by: {Queries(t.ReadBy)}\n\n");
        }
        return sb.ToString();
    }

    private static string Queries(List<string> queries) =>
        queries.Count == 0 ? "-" : string.Join(", ", queries.Order(StringComparer.Ordinal).Select(q => $"`{q}`"));
}
