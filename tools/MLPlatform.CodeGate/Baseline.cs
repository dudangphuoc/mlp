namespace MLPlatform.CodeGate;

public sealed class Baseline(string path)
{
    private const string Header = "# Known gate violations keyed by rule + symbol (not file path). Shrink over time. Generated by: mlp-codegate . --update-baseline";

    public HashSet<string> Entries { get; } = File.Exists(path)
        ? [.. File.ReadAllLines(path).Where(l => l.Length > 0 && !l.StartsWith('#'))]
        : [];

    public void Save(IEnumerable<Finding> findings) =>
        File.WriteAllLines(path, [Header, .. findings.Select(f => f.BaselineEntry).Distinct().Order(StringComparer.Ordinal)]);
}
